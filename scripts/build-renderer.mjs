import { build } from 'esbuild';
import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
process.chdir(root);
if (Number(process.versions.node.split('.')[0]) < 22) throw new Error('Node >=22 is required');
await build({ entryPoints: ['web/renderer.js'], outfile: 'Resources/Web/renderer.js', bundle: true,
  platform: 'browser', format: 'iife', target: 'safari16', minify: true, legalComments: 'inline', charset: 'utf8' });
const lock = JSON.parse(await readFile('package-lock.json', 'utf8'));
const packages = [];
let notices = '# Third-party notices\n\nGenerated by scripts/build-renderer.mjs from exact locked local packages.\nDOMPurify is used under Apache-2.0; its alternative MPL notice is also included.\n\n';
for (const [location, entry] of Object.entries(lock.packages)) {
  if (!location || entry.dev) continue;
  const name = location.replace(/^node_modules\//, '');
  const directory = path.join(root, location);
  const licenses = (await readdir(directory)).filter(n => /^license(?:[-.]|$)/i.test(n)).sort();
  if (!licenses.length) throw new Error(`Missing license: ${name}`);
  const licenseFiles = [];
  for (const license of licenses) {
    const text = await readFile(path.join(directory, license), 'utf8');
    notices += `## ${name}@${entry.version} — ${entry.license}\n\nSource: ${entry.resolved}\nLicense file: ${license}\n\n${text}\n\n`;
    licenseFiles.push({ name: license, sha256: createHash('sha256').update(text).digest('hex') });
  }
  packages.push({ name, version: entry.version, license: entry.license, source: entry.resolved,
    integrity: entry.integrity, metadata: `https://registry.npmjs.org/${encodeURIComponent(name)}/${entry.version}`, licenseFiles });
}
await writeFile('THIRD_PARTY_NOTICES.md', notices);
await mkdir('Resources/Notices', { recursive: true });
await writeFile('Resources/Notices/THIRD_PARTY_NOTICES.md', notices);
const files = ['Resources/Web/renderer.js', 'Resources/Web/shell.html', 'Resources/Web/styles.css', 'Resources/Notices/THIRD_PARTY_NOTICES.md'];
const assets = [];
for (const file of files) {
  const bytes = await readFile(file);
  assets.push({ path: file, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });
}
await writeFile('vendor-manifest.json', JSON.stringify({ schema: 1,
  regeneration: 'npm ci --ignore-scripts --no-audit --no-fund && npm run build',
  buildTool: { name: 'esbuild', version: lock.packages['node_modules/esbuild'].version,
    source: lock.packages['node_modules/esbuild'].resolved, integrity: lock.packages['node_modules/esbuild'].integrity, license: 'MIT' },
  languages: ['javascript', 'typescript', 'json', 'css', 'xml', 'bash', 'python', 'swift'],
  packages, assets }, null, 2) + '\n');
console.log(`Built offline renderer; inventoried ${packages.length} production packages and ${assets.length} assets`);
